<script setup>
// Plant a seed: name the study set, pick a subject and tags, build flashcards by hand or upload a
// document for the AI to turn into flashcards, browse/edit them in the preview, then save.
// Shown after the seed packet is dropped on the garden.
// Emits 'save' with { title, subject, exam_date, tags, cards } and 'cancel'.
import { computed, markRaw, onBeforeUnmount, ref, watch } from 'vue'
import { useGardenStore } from '@/stores/garden'
import { apiFetch } from '@/lib/http'
import { tagColors, tagStyle } from '@/lib/tagColors'
import { VueDatePicker } from '@vuepic/vue-datepicker'
import '@vuepic/vue-datepicker/dist/main.css'
import tulipSvg from '@/assets/foliage/tulip-4.svg'

const props = defineProps({
  busy: { type: Boolean, default: false }, // true while the parent is saving
  error: { type: String, default: '' },
})
const emit = defineEmits(['save', 'cancel'])

const garden = useGardenStore()

// Card limits: up to 50 AI pairs per uploaded file, 200 cards per seed (the server checks 200 too)
const MAX_CARDS = 200
const NEAR_LIMIT = 180
const MAX_AI_PER_FILE = 50
let nextId = 0

// Study Set Details
const title = ref('')
const subject = ref('')
const tags = ref([]) // [{ name, color }]
const tagInput = ref('')
const tagColor = ref(tagColors[0].id) // colour for the next tag
const knownSubjects = computed(() => [...new Set(garden.seeds.map((s) => s.subject).filter(Boolean))]) // suggestions only

// Exam date (optional) belongs to the subject. An existing subject's upcoming date is filled in; a past one is not,
// so it can't block planting. Leaving it blank keeps whatever the subject already has.
// Shown as DD-MM-YYYY, stored as YYYY-MM-DD.
const examDate = ref(null) // YYYY-MM-DD
const now = new Date()
const minExamDate = new Date(now.getFullYear(), now.getMonth(), now.getDate()) // start of today, local
const today = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`
const savedExamDate = computed(() => {
  const date = garden.seeds.find((s) => s.subject === subject.value.trim() && s.exam_date)?.exam_date
  return date && date >= today ? date : ''
})
watch(savedExamDate, (date) => { examDate.value = date || null })
const examPast = computed(() => !!examDate.value && examDate.value < today)
const examHelp = computed(() => {
  const name = subject.value.trim()
  if (savedExamDate.value && examDate.value === savedExamDate.value) return `Saved for all your ${name} seeds.`
  if (savedExamDate.value) return `This changes the exam date for all your ${name} seeds.`
  return name ? `When is your ${name} exam? Optional.` : 'Optional.'
})

function addTag() {
  const name = tagInput.value.trim()
  const taken = tags.value.some((t) => t.name.toLowerCase() === name.toLowerCase())
  if (name && !taken && tags.value.length < 8) tags.value.push({ name, color: tagColor.value })
  tagInput.value = ''
}
// Enter or comma turns the typed text into a chip (Enter must not submit the form)
function onTagKey(e) {
  if (e.key === 'Enter' || e.key === ',') {
    e.preventDefault()
    addTag()
  }
}

// Cards: typed in the builder or generated by the AI from an uploaded file, all in one list.
// fileId is only set on AI cards, so removing a file can remove its cards.
// traps: the 3 trap-answer tiles as typed (blank = none); cleaned into wrong_options when the seed is saved.
const cards = ref([]) // [{ id, fileId?, question, answer, traps }]
const totalCards = computed(() => cards.value.length)
const isFull = computed(() => totalCards.value >= MAX_CARDS)
const overBy = computed(() => totalCards.value - MAX_CARDS)

// Flashcard Builder
const question = ref('')
const answer = ref('')
const traps = ref(['', '', '']) // the new card's trap tiles, typed under the Preview
const drafting = computed(() => !!(question.value.trim() || answer.value.trim()))
const canAddCard = computed(() => question.value.trim() && answer.value.trim() && !isFull.value)
function addCard() {
  if (!canAddCard.value) return
  cards.value.push({ id: nextId++, question: question.value.trim(), answer: answer.value.trim(), traps: traps.value })
  question.value = ''
  answer.value = ''
  traps.value = ['', '', '']
  index.value = cards.value.length - 1
}

// Quiz options, under the Preview: Kahoot-style tiles for the card on screen (the new card, or any added one,
// typed or AI). Its answer is always the correct tile; the user only types traps, and the quiz shuffles all four,
// so the position doesn't matter.
const SHAPES = ['▲', '◆', '●', '■']
const same = (a, b) => a.trim().toLowerCase() === b.trim().toLowerCase()
// trimmed, no blanks, none equal to the answer, no repeats (case-insensitive), at most 3
function cleanTraps(list, correct) {
  const kept = []
  for (const t of list.map((x) => x.trim())) {
    if (t && !same(t, correct) && !kept.some((k) => same(k, t))) kept.push(t)
  }
  return kept.slice(0, 3)
}
// why a typed trap will be skipped, shown under its tile
function trapNote(list, i, correct) {
  const t = list[i].trim()
  if (!t) return ''
  if (correct.trim() && same(t, correct)) return 'Same as the answer, so it will be skipped.'
  if (list.slice(0, i).some((x) => x.trim() && same(x, t))) return 'Repeated, so it will be skipped.'
  return ''
}
// the tiles shown under the Preview: the new card while typing, otherwise the card on screen
const tileTraps = computed(() => (showDraft.value ? traps.value : current.value?.traps))
const tileAnswer = computed(() => (showDraft.value ? answer.value : editing.value ? editing.value.answer : current.value?.answer ?? ''))
const trapCount = computed(() => (tileTraps.value ? cleanTraps(tileTraps.value, tileAnswer.value).length : 0))

// Upload a file: each file is sent to the server, which returns AI-written pairs
const ACCEPTED = ['txt', 'pdf', 'pptx', 'docx']
const MAX_MB = 50
const fileInput = ref(null)
const files = ref([]) // [{ id, file, name, size, status: 'generating' | 'done' | 'failed', error, requested, count, confirming }]
const controllers = new Map() // file id -> AbortController for its running request
const dragging = ref(false)
const fileError = ref('')
const extOf = (name) => name.split('.').pop().toLowerCase()
const generating = computed(() => files.value.some((f) => f.status === 'generating'))
const failedFiles = computed(() => files.value.filter((f) => f.status === 'failed'))
const pairsFrom = (f) => cards.value.filter((c) => c.fileId === f.id).length

function addFiles(list) {
  fileError.value = ''
  for (const f of list) {
    const ext = extOf(f.name)
    if (ext === 'ppt') fileError.value = `${f.name}: please save it as PPTX and upload again.`
    else if (!ACCEPTED.includes(ext)) fileError.value = `${f.name} isn't a TXT, PDF, PPTX or DOCX file.`
    else if (f.size > MAX_MB * 1024 * 1024) fileError.value = `${f.name} is over ${MAX_MB}MB.`
    else if (isFull.value) fileError.value = `This seed is full (${MAX_CARDS} cards). Delete some cards to upload another file.`
    else if (!files.value.some((x) => x.name === f.name && x.size === f.size)) {
      files.value.push({ id: nextId++, file: markRaw(f), name: f.name, size: f.size, status: 'generating', error: '', requested: 0, count: 0, confirming: false })
      generate(files.value[files.value.length - 1])
    }
  }
}
function onPick(e) {
  addFiles(e.target.files)
  e.target.value = '' // lets the same file be picked again after removing it
}
function onDrop(e) {
  dragging.value = false
  addFiles(e.dataTransfer.files)
}
function fileSize(bytes) {
  return bytes < 1024 * 1024 ? `${Math.max(1, Math.round(bytes / 1024))} KB` : `${(bytes / 1024 / 1024).toFixed(1)} MB`
}
function fileStatus(f) {
  if (f.status === 'generating') return 'Generating…'
  if (f.status === 'failed') return f.error
  const n = pairsFrom(f)
  return `${n} ${n === 1 ? 'pair' : 'pairs'}${f.requested < MAX_AI_PER_FILE && f.count === f.requested ? ' (seed limit reached)' : ''}`
}

// Asks for at most 50 pairs, or fewer when the seed is close to 200 cards
// (room already promised to other files still generating counts as taken)
async function generate(f) {
  const reserved = files.value.filter((x) => x !== f && x.status === 'generating').reduce((n, x) => n + x.requested, 0)
  const room = MAX_CARDS - totalCards.value - reserved
  if (room <= 0) {
    f.status = 'failed'
    f.error = `This seed is full (${MAX_CARDS} cards). Delete some cards, then try again.`
    return
  }
  f.requested = Math.min(MAX_AI_PER_FILE, room)
  f.status = 'generating'
  f.error = ''
  const controller = new AbortController()
  controllers.set(f.id, controller)

  const body = new FormData()
  body.append('file', f.file)
  body.append('maxCards', String(f.requested))
  body.append('existingQuestions', JSON.stringify(cards.value.map((c) => c.question)))
  try {
    const { cards: generated } = await apiFetch('/api/seeds/generate', { method: 'POST', body, signal: controller.signal })
    const first = cards.value.length
    // the AI's trap answers fill the tiles, still editable; padded to 3 tiles
    const tilesFrom = (wrong = []) => [...wrong, '', '', ''].slice(0, 3)
    cards.value.push(...generated.map((c) => ({ id: nextId++, fileId: f.id, question: c.question, answer: c.answer, traps: tilesFrom(c.wrong_options) })))
    f.status = 'done'
    f.count = generated.length
    if (!editing.value) index.value = first // jump to this file's first pair
  } catch (e) {
    if (controller.signal.aborted) return // the file was removed while generating
    f.status = 'failed'
    f.error = e instanceof Error ? e.message : String(e)
  } finally {
    controllers.delete(f.id)
  }
}

// A file with pairs asks first (f.confirming shows the prompt); otherwise it goes straight away
function removeFile(f) {
  if (f.status === 'done' && pairsFrom(f) > 0) f.confirming = true
  else dropFile(f)
}
// Removes the file and every pair generated from it (edited ones too)
function dropFile(f) {
  controllers.get(f.id)?.abort()
  cards.value = cards.value.filter((c) => c.fileId !== f.id)
  files.value = files.value.filter((x) => x !== f)
  stopEditing()
  clampIndex()
}

onBeforeUnmount(() => controllers.forEach((c) => c.abort()))

// Preview: all cards in one list. While a card is being typed, it is shown live.
// While a file is generating, a loading box shows if there is nothing else to show, otherwise a short note.
const index = ref(0)
const current = computed(() => cards.value[index.value] ?? null)
const showDraft = computed(() => drafting.value)
const showLoading = computed(() => generating.value && !showDraft.value && cards.value.length === 0)
const canBrowse = computed(() => !showDraft.value && cards.value.length > 0)

function clampIndex() {
  index.value = Math.min(index.value, Math.max(0, cards.value.length - 1))
}
function go(step) {
  stopEditing()
  index.value = Math.min(Math.max(0, index.value + step), cards.value.length - 1)
}
watch(drafting, (d) => { if (d) stopEditing() })

// Edit / delete the pair on screen
const editing = ref(null) // { question, answer } while editing the current pair (its trap tiles are always editable)
const canSaveEdit = computed(() => editing.value?.question.trim() && editing.value?.answer.trim())
function startEdit() {
  editing.value = { question: current.value.question, answer: current.value.answer }
}
function stopEditing() {
  editing.value = null
}
function saveEdit() {
  if (!canSaveEdit.value) return
  current.value.question = editing.value.question.trim()
  current.value.answer = editing.value.answer.trim()
  stopEditing()
}
function deleteCurrent() {
  stopEditing()
  cards.value.splice(index.value, 1)
  clampIndex()
}

// Progress: 1 name it, 2 add cards, 3 review and save
const hasDetails = computed(() => title.value.trim() && subject.value.trim())
const hasCards = computed(() => totalCards.value > 0 || canAddCard.value)
const step = computed(() => (!hasDetails.value ? 1 : !hasCards.value ? 2 : 3))
const stepText = ['Name your study set and subject.', 'Add at least one flashcard or upload a study document.', 'Review your cards, then plant it.']

const plantNote = computed(() => {
  if (examPast.value) return { error: true, text: 'Pick an exam date from today onwards, or leave it blank.' }
  if (overBy.value > 0) return { error: true, text: `Delete ${overBy.value} ${overBy.value === 1 ? 'card' : 'cards'} to plant. A seed can have at most ${MAX_CARDS}.` }
  if (generating.value) return { error: false, text: 'Wait until your file finishes generating, then plant it.' }
  return null
})
const canPlant = computed(() => step.value === 3 && !props.busy && !generating.value && overBy.value <= 0 && !examPast.value)

function save() {
  if (!canPlant.value) return
  addCard() // a filled-in card that wasn't added with + yet is kept, not lost
  addTag() // same for a typed tag that wasn't added with Enter
  emit('save', {
    title: title.value.trim(), subject: subject.value.trim(), exam_date: examDate.value || undefined, tags: tags.value,
    cards: cards.value.map(({ question, answer, traps }) => ({ question, answer, wrong_options: cleanTraps(traps, answer) })),
  })
}
</script>

<template>
  <form class="plant-form" data-testid="plant-seed-form" @submit.prevent="save">
    <header class="top mt-4">
      <img class="top-art" :src="tulipSvg" alt="" />
      <div>
        <h3>Plant a new seed</h3>
        <p class="text-body-small sub">It will grow into a tulip as you revise.</p>
      </div>
    </header>
    <!-- Progress -->
    <section class="sticky-top" data-testid="seed-progress">
      <div class="progress-head">
        <strong>Step {{ step }} of 3</strong>
        <span>{{ Math.round((step / 3) * 100) }}%</span>
      </div>
      <div class="progress" role="progressbar">
        <div class="progress-fill" :style="{ width: (step / 3) * 100 + '%' }" />
      </div>
      <p class="help">{{ stepText[step - 1] }}</p>
    </section>

    <!-- Study Set Details -->
    <section class="card-box">
      <h4>Study set details</h4>
      <label class="field">
        <span class="text-label-field">Study set name</span>
        <input v-model="title" maxlength="80" placeholder="e.g. WAD2 Lab Test 1 Revision" data-testid="seed-title" />
      </label>
      <label class="field">
        <span class="text-label-field">Subject</span>
        <input v-model="subject" maxlength="60" list="seed-subjects" placeholder="e.g. WAD2" data-testid="seed-subject" />
        <datalist id="seed-subjects">
          <option v-for="s in knownSubjects" :key="s" :value="s" />
        </datalist>
      </label>
      <div class="field">
        <label class="text-label-field" for="seed-exam-date">Exam date</label>
        <VueDatePicker
          v-model="examDate" model-type="yyyy-MM-dd" :formats="{ input: 'dd-MM-yyyy' }"
          :text-input="{ format: 'dd-MM-yyyy' }" placeholder="DD-MM-YYYY" :min-date="minExamDate"
          :time-config="{ enableTimePicker: false }" auto-apply teleport
          :ui="{ input: 'exam-input' }" :input-attrs="{ id: 'seed-exam-date' }" data-testid="seed-exam-date"
        />
        <span class="help" data-testid="seed-exam-help">{{ examHelp }}</span>
      </div>
      <label class="field">
        <span class="text-label-field">Tags</span>
        <input
          v-model="tagInput" maxlength="20" placeholder="Type a tag, pick a colour, press Enter"
          data-testid="seed-tag-input" @keydown="onTagKey"
        />
      </label>
      <div class="colours" role="radiogroup" aria-label="Tag colour">
        <button
          v-for="c in tagColors" :key="c.id" type="button" class="tag-pill"
          :class="{ selected: tagColor === c.id }" :style="tagStyle(c.id, tagColor === c.id)"
          role="radio" :aria-checked="tagColor === c.id" :aria-label="c.label"
          :data-testid="`tag-color-${c.id}`" @click="tagColor = c.id"
        >
          <span v-if="tagColor === c.id" aria-hidden="true">✓</span>{{ tagInput.trim() || 'Tag' }}
        </button>
      </div>
      <ul v-if="tags.length" class="chips">
        <li v-for="t in tags" :key="t.name" class="tag-pill" :style="tagStyle(t.color)">
          {{ t.name }}
          <button type="button" :aria-label="`Remove tag ${t.name}`" @click="tags = tags.filter((x) => x !== t)">×</button>
        </li>
      </ul>
    </section>

    <!-- Flashcard Builder and Upload a file, side by side so the Preview stays close -->
    <div class="row g-3">
    <div class="col-sm-6 d-flex">
    <section class="card-box w-100">
      <div class="card-head">
        <h4>Flashcard builder</h4>
        <button type="button" class="plus" :disabled="!canAddCard" aria-label="Add card" data-testid="card-add" @click="addCard">+</button>
      </div>
      <div class="qa">
        <label class="field">
          <span class="text-label-field">Question</span>
          <textarea v-model="question" rows="3" maxlength="500" placeholder="How do you centre text horizontally in CSS?" data-testid="card-question" />
        </label>
        <label class="field">
          <span class="text-label-field">Answer</span>
          <textarea v-model="answer" rows="3" maxlength="500" placeholder="Use text-align: center; on the element." data-testid="card-answer" />
        </label>
      </div>
      <p class="count" :class="{ near: totalCards >= NEAR_LIMIT && overBy <= 0, over: overBy > 0 }" data-testid="card-count">
        <span class="badge text-label-caption">NEW</span>
        <span>
          {{ totalCards }} / {{ MAX_CARDS }} cards in this set<template v-if="overBy > 0">, delete {{ overBy }} to plant</template><template v-else-if="isFull">, this seed is full</template><template v-else-if="totalCards >= NEAR_LIMIT">, you're near the limit</template>
        </span>
      </p>
    </section>
    </div>

    <!-- Upload a file -->
    <div class="col-sm-6 d-flex">
    <section class="card-box w-100">
      <div>
        <h4>Upload a file</h4>
        <p class="help">Select and upload your notes or slides.</p>
      </div>
      <div
        class="dropzone" :class="{ dragging: dragging && !isFull, full: isFull }" data-testid="file-dropzone"
        @dragover.prevent="dragging = true" @dragleave="dragging = false" @drop.prevent="onDrop"
      >
        <template v-if="isFull">
          <p class="drop-title">This seed is full ({{ MAX_CARDS }} cards)</p>
          <p class="help">Delete some cards to upload another file.</p>
        </template>
        <template v-else>
          <p class="drop-title">Choose a file or drag &amp; drop it here</p>
          <p class="help">TXT, PDF, PPTX and DOCX supported, up to {{ MAX_MB }}MB</p>
        </template>
        <button type="button" class="ghost-btn text-button" :disabled="isFull" data-testid="file-browse" @click="fileInput.click()">Browse file</button>
        <input
          ref="fileInput" type="file" class="visually-hidden" multiple
          accept=".txt,.pdf,.pptx,.docx,text/plain,application/pdf,application/vnd.openxmlformats-officedocument.presentationml.presentation,application/vnd.openxmlformats-officedocument.wordprocessingml.document"
          data-testid="file-input" @change="onPick"
        />
      </div>
      <p v-if="fileError" class="error" data-testid="file-error">{{ fileError }}</p>
      <ul v-if="files.length" class="file-list">
        <li v-for="f in files" :key="f.id" data-testid="file-row">
          <span class="file-type" :class="`type-${extOf(f.name).slice(0, 3)}`">{{ extOf(f.name).toUpperCase() }}</span>
          <span class="file-meta">
            <span class="file-name">{{ f.name }}</span>
            <span class="help" :class="{ failed: f.status === 'failed' }">{{ fileSize(f.size) }} · {{ fileStatus(f) }}</span>
          </span>
          <button v-if="f.status === 'failed'" type="button" class="mini-btn" @click="generate(f)">Try again</button>
          <button type="button" class="remove" :aria-label="`Remove ${f.name}`" @click="removeFile(f)">×</button>
          <div v-if="f.confirming" class="confirm" role="alert" data-testid="file-confirm">
            <p>Delete this file and its {{ pairsFrom(f) }} question/answer {{ pairsFrom(f) === 1 ? 'pair' : 'pairs' }}? Edited pairs are deleted too.</p>
            <div class="confirm-actions">
              <button type="button" class="mini-btn" @click="f.confirming = false">Cancel</button>
              <button type="button" class="mini-btn danger" data-testid="file-confirm-delete" @click="dropFile(f)">Delete</button>
            </div>
          </div>
        </li>
      </ul>
    </section>
    </div>
    </div>

    <!-- Preview -->
    <section class="card-box">
      <div class="preview-head">
        <h4>Preview</h4>
        <div v-if="canBrowse" class="arrows">
          <button type="button" class="arrow" :disabled="index === 0" aria-label="Previous pair" data-testid="pair-prev" @click="go(-1)">&lt;</button>
          <button type="button" class="arrow" :disabled="index >= cards.length - 1" aria-label="Next pair" data-testid="pair-next" @click="go(1)">&gt;</button>
        </div>
      </div>
      <p v-if="generating && !showLoading" class="help generating" role="status" data-testid="preview-generating">
        <span class="spinner small" aria-hidden="true" />Generating cards from your file…
      </p>

      <div v-if="showLoading" class="loading" role="status" data-testid="preview-loading">
        <span class="spinner" aria-hidden="true" />
        <p class="drop-title">Loading, please wait…</p>
        <p class="help">Reading your document and writing flashcards. Long documents can take a minute.</p>
      </div>

      <template v-else>
        <div v-for="f in failedFiles" :key="f.id" class="gen-error" role="alert">
          <p class="error">{{ f.name }}: {{ f.error }}</p>
          <button type="button" class="mini-btn" @click="generate(f)">Try again</button>
        </div>

        <div v-if="showDraft || current" class="flash" data-testid="card-preview">
          <div class="face">
            <span v-if="subject" class="subject-tag">{{ subject }}</span>
            <span class="text-label-caption caption">Question</span>
            <textarea v-if="editing" v-model="editing.question" rows="4" maxlength="500" aria-label="Edit question" data-testid="edit-question" />
            <p v-else class="big">{{ showDraft ? question : current.question }}</p>
          </div>
          <div class="face answer">
            <span v-if="subject" class="subject-tag">{{ subject }}</span>
            <span class="text-label-caption caption">Answer</span>
            <textarea v-if="editing" v-model="editing.answer" rows="4" maxlength="500" aria-label="Edit answer" data-testid="edit-answer" />
            <p v-else>{{ showDraft ? answer : current.answer }}</p>
          </div>
        </div>
        <details v-if="tileTraps" class="quiz-options" data-testid="quiz-options">
          <summary>
            <span class="text-label-field">Quiz options</span>
            <span class="help">Optional{{ trapCount ? ` · ${trapCount} trap ${trapCount === 1 ? 'answer' : 'answers'}` : '' }}</span>
          </summary>
          <div class="tiles">
            <div class="tile correct">
              <span class="tile-shape" aria-hidden="true">{{ SHAPES[0] }}</span>
              <span class="tile-text" :class="{ empty: !tileAnswer.trim() }" data-testid="tile-correct">{{ tileAnswer.trim() || 'Your answer shows here' }}</span>
              <span class="tile-check" aria-label="Correct answer">✓</span>
            </div>
            <label v-for="(t, i) in tileTraps" :key="i" class="tile">
              <span class="tile-shape" aria-hidden="true">{{ SHAPES[i + 1] }}</span>
              <input v-model="tileTraps[i]" maxlength="500" :placeholder="`Trap answer ${i + 1}`" :aria-label="`Trap answer ${i + 1}`" :data-testid="`card-trap-${i}`" />
              <span v-if="trapNote(tileTraps, i, tileAnswer)" class="tile-note">{{ trapNote(tileTraps, i, tileAnswer) }}</span>
            </label>
          </div>
        </details>
        <p v-else class="help">
